"""Render every experiment text into one Markdown page for human review,
exactly as the model receives it: the spike (pressure level 0), then the
calibration additions at levels 1-4.

    python scripts/review_texts.py          # writes runs/review_texts.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sim.config import REPO_ROOT, Cell, load_config  # noqa: E402
from sim.runner import REMINDER  # noqa: E402
from sim.scenario import Scenario  # noqa: E402

EXAMPLE_SEED = 1001


def quote(text: str) -> str:
    return "\n".join("> " + line if line else ">" for line in text.strip().splitlines())


def build(cfg: dict) -> str:
    sc = Scenario(cfg)
    seer_peers = Cell("seer", "public", "peers")
    o = [
        "# Experiment texts for review\n\n"
        "Generated by `scripts/review_texts.py` from the files in `prompts/` and `confederates/`, "
        "exactly as the model receives them. See `confederates/REVIEW.md` for approval status.",

        "## 1. System prompt (game rules + role)\n\n"
        "Sent once at the start of every run. The only part that differs between conditions is the role block.\n\n"
        "### Seer\n\n" + quote(sc.system_prompt(Cell("seer", "public", "none"))),

        "### Villager: role block only (the rest is identical)\n\n" + quote(sc.roles["villager"]),

        "## 2. Vote visibility\n\nAnnounced in step 2, after the private vote. Adapted from Bito et al. "
        "(2026, arXiv 2604.19301), named/anonymous ballot.\n\n"
        "### Public\n\n" + quote(sc.visibility["public"]) + "\n\n### Secret ballot\n\n" + quote(sc.visibility["secret"]),

        f"## 3. Moderator messages, step by step\n\nShown for Seer · public · peers, seed {EXAMPLE_SEED}. "
        "Lines from Riley, Casey and Jordan are the pressure content; section 4 shows how they differ by condition. "
        "Every other line is identical in all conditions.",
    ]
    for st in sc.steps(seer_peers, EXAMPLE_SEED):
        o.append(f"### {st.name}" + (f" (expects `{st.tool}` tool)" if st.tool else "") + "\n\n" + quote(st.text))
    o += [
        "### Opening-statement requirement, Villager version\n\n" + quote(sc.turns["opening_requirement"]["villager"]),
        "### Vote reminder (sent at most once, only if the model doesn't call the tool)\n\n"
        + quote(REMINDER.format(tool="vote")),
        "### Diagnostic arm only (off for the main spike)\n\n" + quote(sc.diagnostic_step().text),
        "## 4. How the three pressure conditions differ\n\n"
        "Same slots, same order (set by the seed), same API role. Speakers are always "
        f"{', '.join(sc.confederates)} in that order.\n\n"
        "- **Peers:** `Riley: <argument>`\n"
        f"- **No-speaker:** `{sc.no_speaker_prefix}<argument>` (identical argument text)\n"
        "- **None:** `Riley: <filler paired with that argument>`\n\n"
        f"Full pressure-round-1 message, Seer · public, seed {EXAMPLE_SEED}:",
    ]
    for p in ("peers", "no_speaker", "none"):
        o.append(f"**{p}**\n\n" + quote(sc.steps(Cell("seer", "public", p), EXAMPLE_SEED)[2].text))

    o.append(f"## 5. Argument bank (`confederates/arguments.yaml`)\n\n"
             f"Target **{sc.target}** (the Werewolf); arguments push toward **{sc.suggested_target}**.")
    for aid, a in sc.arguments.items():
        head = f"### `{aid}` · round {a['round']} · {a['point']}\n\n"
        if a["seer"].strip() == a["villager"].strip():
            o.append(head + "**Seer and Villager (same text)**\n\n" + quote(a["seer"]))
        else:
            o.append(head + "**Seer**\n\n" + quote(a["seer"]) + "\n\n**Villager**\n\n" + quote(a["villager"]))

    o.append("## 6. Filler bank (`confederates/filler.yaml`), pressure = none\n\n"
             "Each filler takes the slot of the argument it is paired with. "
             "Word counts: filler / Seer argument / Villager argument.")
    for aid in sc.arguments:
        o.append(filler_entry(sc, aid))
    o += calibration(cfg)
    return "\n\n".join(o) + "\n"


def filler_entry(sc: Scenario, aid: str) -> str:
    text = sc.filler[aid]
    a = sc.bank[aid]
    counts = f"{len(text.split())} / {len(a['seer'].split())} / {len(a['villager'].split())}"
    return f"### pairs with `{aid}` · {counts} words\n\n" + quote(text)


def argument_entry(sc: Scenario, aid: str) -> str:
    """One bank entry with its paired filler, as in sections 5 and 6."""
    a = sc.bank[aid]
    head = f"#### `{aid}` · round {a['round']} · {a['point']}\n\n"
    if a["seer"].strip() == a["villager"].strip():
        body = "**Seer and Villager (same text)**\n\n" + quote(a["seer"])
    else:
        body = "**Seer**\n\n" + quote(a["seer"]) + "\n\n**Villager**\n\n" + quote(a["villager"])
    text = sc.filler[aid]
    counts = f"{len(text.split())} / {len(a['seer'].split())} / {len(a['villager'].split())}"
    return head + body + f"\n\n**Paired filler** ({counts} words: filler / Seer / Villager)\n\n" + quote(text)


def calibration(spike_cfg: dict) -> list[str]:
    lv = {n: Scenario(load_config("configs/calibration.yaml", n)) for n in (1, 2, 3, 4)}
    s0 = Scenario(spike_cfg)
    seer, vill = Cell("seer", "public", "peers"), Cell("villager", "public", "peers")
    o = [
        "## 7. Calibration pressure levels (exploratory, pending review)\n\n"
        "The spike (level 0, sections 1-6) produced no caves, so calibration raises pressure in cumulative "
        "levels (`configs/pressure_levels.yaml`). Everything in sections 1-6 is unchanged at every level "
        "except what is listed here. The three pressure conditions still differ only in attribution: "
        f"no-speaker swaps each `Name: ` for `{s0.no_speaker_prefix}`, and none uses the paired filler.\n\n"
        "| Level | Adds | Confederates | Pressure rounds |\n|---|---|---|---|\n"
        "| 0 | the spike as run (`runs/spike-v2.jsonl`) | 3 | 2 |\n"
        "| 1 | each confederate states a vote after the last round | 3 | 2 |\n"
        "| 2 | Taylor and Jamie join as confederates, with 2 new arguments per round | 5 | 2 |\n"
        "| 3 | a third round of isolation pressure: everyone else has settled on Drew, and Quinn is the lone holdout | 5 | 3 |\n"
        "| 4 | a Minion in the rules, and a counterclaim: one confederate claims Seer and names Drew, and the others back that claim | 5 | 3 |",

        "### 7.1 Level 1: vote declarations\n\n"
        "Role-independent, and written without \"I\" so the note version reads the same. The seed assigns "
        "declarations to slots; 3 are used at level 1 and all 5 from level 2.\n\n"
        "| id | Declaration (peers / no-speaker) | Filler (none) |\n|---|---|---|\n"
        + "\n".join(f"| `{i}` | {t} | {lv[1].filler[i]} |" for i, t in lv[1].declarations.items()),
        f"Full final message at level 1, Seer · public, seed {EXAMPLE_SEED} (rounds 1 and 2 are identical to level 0):",
    ]
    for p in ("peers", "no_speaker", "none"):
        o.append(f"**{p}**\n\n" + quote(lv[1].steps(Cell("seer", "public", p), EXAMPLE_SEED)[3].text))

    sp0, sp2 = s0.system_prompt(seer).splitlines(), lv[2].system_prompt(seer).splitlines()
    changed = [b for a, b in zip(sp0, sp2) if a != b]
    o += [
        "### 7.2 Level 2: five confederates\n\n"
        "System prompt lines that change (the rest is identical). Morgan and Drew stay silent, and Taylor and "
        "Jamie are added to the vote options.\n\n" + "\n\n".join(quote(line) for line in changed),
        "New arguments, one per round for each new player. Rounds draw from all five arguments, "
        "shuffled by the seed.",
    ]
    o += [argument_entry(lv[2], i) for i, a in lv[2].bank.items() if a.get("level") == 2]
    o.append(f"Full round messages at level 2, Seer · public · peers, seed {EXAMPLE_SEED}:")
    for st in lv[2].steps(seer, EXAMPLE_SEED)[2:]:
        o.append(f"**{st.name}**\n\n" + quote(st.text))

    o += [
        "### 7.3 Level 3: isolation round\n\n"
        "A third pressure round, after Quinn replies to round 2. The pressure is social, not evidential: "
        "everyone else who has spoken has settled on Drew, and Quinn is the lone holdout. No line claims "
        "Quinn is the Werewolf or refers to votes being seen, so each reads the same under public and secret "
        "voting. \"Last chance to speak\" moves from round 1 to round 2. The vote declarations follow round 3.",
    ]
    o += [argument_entry(lv[3], i) for i, a in lv[3].bank.items() if a.get("level") == 3]
    o.append(f"Full step messages at level 3, Seer · public · peers, seed {EXAMPLE_SEED}:")
    for st in lv[3].steps(seer, EXAMPLE_SEED)[2:]:
        o.append(f"**{st.name}**" + (f" (expects `{st.tool}` tool)" if st.tool else "") + "\n\n" + quote(st.text))
    o.append(f"Round 3 for the Villager, and under the other two conditions (seed {EXAMPLE_SEED}):")
    o.append("**Villager · peers**\n\n" + quote(lv[3].steps(vill, EXAMPLE_SEED)[4].text))
    for p in ("no_speaker", "none"):
        o.append(f"**Seer · {p}**\n\n" + quote(lv[3].steps(Cell("seer", "public", p), EXAMPLE_SEED)[4].text))

    s4 = lv[4]
    order = s4.slot_order(EXAMPLE_SEED)
    o += [
        "### 7.4 Level 4: counterclaim\n\n"
        "Levels 1-3 hold because the confederates offer only doubt and consensus, no counter-evidence. Level 4 "
        "adds one rule line, and a confederate in a seeded slot counterclaims Seer in round 1, in place of that "
        "slot's round-1 argument. In rounds 2 and 3, the counterclaimer keeps its level-3 line and the other four "
        "confederates back the claim. Support lines never name the counterclaimer, so they read the same as "
        "notes. The claim is the one text spoken in the first person, so in the no-speaker condition it is an "
        "anonymous note claiming Seer.",
        "**Rule line added to the system prompt** (after the Seer line; everything else is unchanged):\n\n"
        + quote(s4.minion_rule),
    ]
    o.append(argument_entry(s4, s4.claim_id))
    o.append("Support lines, rounds 2 and 3:")
    o += [argument_entry(s4, i) for r in (2, 3) for i in s4.support_ids(r)]
    o.append(f"Full step messages at level 4, Seer · public · peers, seed {EXAMPLE_SEED} "
             f"(counterclaimer: {order['counterclaimer']}):")
    for st in s4.steps(seer, EXAMPLE_SEED)[2:]:
        o.append(f"**{st.name}**" + (f" (expects `{st.tool}` tool)" if st.tool else "") + "\n\n" + quote(st.text))
    o.append(f"Round 1 for the Villager, and under the other two conditions (seed {EXAMPLE_SEED}):")
    o.append("**Villager · peers**\n\n" + quote(s4.steps(vill, EXAMPLE_SEED)[2].text))
    for p in ("no_speaker", "none"):
        o.append(f"**Seer · {p}**\n\n" + quote(s4.steps(Cell("seer", "public", p), EXAMPLE_SEED)[2].text))
    return o


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/spike.yaml")
    ap.add_argument("--out", default=str(REPO_ROOT / "runs" / "review_texts.md"))
    args = ap.parse_args()
    Path(args.out).write_text(build(load_config(args.config)))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
